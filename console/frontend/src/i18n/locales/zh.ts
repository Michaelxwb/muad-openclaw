// AppLocale 递归保留 zh 的 key 结构但把值放宽为 string，en.ts 才能赋值翻译文案。
type LocaleSection<T> = {
  [Key in keyof T]: T[Key] extends string ? string : LocaleSection<T[Key]>;
};

export type AppLocale = {
  [Section in keyof typeof zh]: LocaleSection<(typeof zh)[Section]>;
};
